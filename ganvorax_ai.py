# Stage 5: Intelligent Job Recommendation Engine

def recommend_jobs(resume_text, top_n=3):

    # Step 1: Clean candidate resume
    cleaned_resume = clean_text(resume_text)

    # Step 2: Convert resume into TF-IDF vector
    resume_vector = tfidf.transform([cleaned_resume])

    # Step 3: Calculate similarity with job dataset
    scores = cosine_similarity(
        resume_vector,
        tfidf_matrix
    ).flatten()

    # Step 4: Create recommendation results
    results = df[[
        "Job_ID", "Job_Title", "Company"
    ]].copy()

    results["Match_Score"] = scores * 100

    # Step 5: Rank jobs
    results = results.sort_values(
        by="Match_Score",
        ascending=False
    )

    # Step 6: Return top recommendations
    return results.head(top_n).reset_index(drop=True)



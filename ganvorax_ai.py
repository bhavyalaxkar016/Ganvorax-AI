# Stage 6: Skill Gap Analysis Function

def analyze_skill_gap(resume_text, job_title):

    # Clean candidate resume
    cleaned_resume = clean_text(resume_text)

    # Find selected job
    job = df[df["Job_Title"] == job_title]

    if job.empty:
        print("Job title not found!")
        return None

    # Get required skills
    required_text = clean_text(job.iloc[0]["Skills"])

    # Identify required skills from database
    required_skills = [
        skill for skill in skill_database
        if skill.lower() in required_text
    ]

    # Identify candidate skills
    candidate_skills = [
        skill for skill in skill_database
        if skill.lower() in cleaned_resume
    ]

    # Find matching skills
    matched_skills = [
        skill for skill in required_skills
        if skill in candidate_skills
    ]

    # Find missing skills
    missing_skills = [
        skill for skill in required_skills
        if skill not in candidate_skills
    ]

    # Calculate skill coverage
    if len(required_skills) > 0:
        coverage = (
            len(matched_skills) / len(required_skills)
        ) * 100
    else:
        coverage = 0

    # Display results
    print("GANVORAX AI - SKILL GAP ANALYSIS")
    print("--------------------------------")

    print("Selected Job:", job_title)

    print("\nRequired Skills:", required_skills)

    print("\nMatched Skills:", matched_skills)

    print("\nMissing Skills:", missing_skills)

    print("\nSkill Coverage:", round(coverage, 2), "%")

    return {
        "Required Skills": required_skills,
        "Matched Skills": matched_skills,
        "Missing Skills": missing_skills,
        "Skill Coverage": round(coverage, 2)
    }

